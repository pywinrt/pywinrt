using System.CodeDom.Compiler;
using System.Text.Json;
using System.Text.Json.Serialization;

/// <summary>
/// What one generator run contributes to the shape census.
/// </summary>
sealed class CensusFragment
{
    /// <summary>
    /// How many members have each forward shape, by shape key.
    /// </summary>
    [JsonPropertyName("forward")]
    public SortedDictionary<string, int> Forward { get; set; } = new(StringComparer.Ordinal);

    /// <summary>
    /// The <c>slot:shape</c> pairs that a WinRT caller can enter, which is what
    /// a reverse trampoline is instantiated for.
    /// </summary>
    [JsonPropertyName("reverse")]
    public SortedSet<string> Reverse { get; set; } = new(StringComparer.Ordinal);

    /// <summary>
    /// The WinRT structs behind each by-value struct layout, so that the
    /// generated file can name them.
    /// </summary>
    [JsonPropertyName("structs")]
    public SortedDictionary<string, SortedSet<string>> Structs { get; set; } =
        new(StringComparer.Ordinal);

    [JsonPropertyName("implementable_interfaces")]
    public int ImplementableInterfaces { get; set; }

    [JsonPropertyName("delegates")]
    public int Delegates { get; set; }
}

/// <summary>
/// How far the census had grown at the end of one revision.
/// </summary>
sealed class CensusRevision
{
    [JsonPropertyName("shapes")]
    public int Shapes { get; set; }

    [JsonPropertyName("reverse_shapes")]
    public int ReverseShapes { get; set; }
}

/// <summary>
/// The shape census merged over every generator run, and the source of
/// <c>shapes-generated.h</c>.
/// </summary>
/// <remarks>
/// This is kept as a file of its own, next to the generated
/// <c>shapes-generated.h</c>, for two reasons. A run cannot see all of the
/// metadata at once - WinUI 2 and the Windows App SDK both define
/// <c>Microsoft.UI.Xaml.Controls</c>, so they are generated by separate runs
/// with separate metadata resolvers - so the runs have to merge somewhere. And
/// the shape ids have to be <em>append-only</em>: a
/// projection package carries the id of each member's shape, the runtime
/// resolves it by indexing the trampoline table, and a package is allowed to run
/// against any later runtime, so a shape keeps the id it was first given even
/// when the metadata it came from is gone.
/// </remarks>
sealed class Census
{
    /// <summary>
    /// The layout of this file. Version 2 keys the fragments by family
    /// rather than by Python package, and a version 1 census is refused
    /// rather than read: its fragments would be dropped in silence and the
    /// trampolines they account for would go missing from the header.
    /// </summary>
    public const int CurrentVersion = 2;

    [JsonPropertyName("version")]
    public int Version { get; set; } = CurrentVersion;

    /// <summary>
    /// Which census this is. It is generated once, when the file is created,
    /// and is never changed afterwards.
    /// </summary>
    /// <remarks>
    /// A table carries the lineage of the census its shape ids were assigned
    /// by, and a runtime refuses a table whose lineage is not the one its own
    /// trampolines were instantiated from. It is an identity rather than a
    /// hash of the contents because the census grows every time another winmd
    /// is projected while every id it has already issued keeps its meaning: a
    /// package generated against this census as it stood has to go on loading
    /// against a runtime built from it after it has grown.
    /// </remarks>
    [JsonPropertyName("lineage")]
    public string Lineage { get; set; } = "";

    /// <summary>
    /// How many times ids have been appended to this census.
    /// </summary>
    /// <remarks>
    /// This is what the lineage on its own misses. Someone who starts from
    /// this census and lets a run of their own extend it keeps the lineage,
    /// and every id appended past the highest one a given runtime knows would
    /// mis-dispatch. A table records the revision it needs and the runtime
    /// refuses anything ahead of its own, which costs none of the forward
    /// compatibility above because a lower revision is still a prefix of the
    /// higher one.
    /// </remarks>
    [JsonPropertyName("revision")]
    public int Revision { get; set; }

    /// <summary>
    /// How many ids the census had at the end of each revision, oldest first.
    /// </summary>
    /// <remarks>
    /// A table needs the ids it names and nothing else, so this is what lets
    /// it say the oldest revision that has them rather than whichever one the
    /// census happened to stand at when it was written. Without it a
    /// namespace that has not changed in years would be renumbered, and would
    /// claim to need a newer runtime, every time some unrelated namespace
    /// contributed a shape.
    /// </remarks>
    [JsonPropertyName("revisions")]
    public List<CensusRevision> Revisions { get; set; } = [];

    /// <summary>
    /// The id of each forward shape. Append-only: an id is never reused and
    /// never renumbered.
    /// </summary>
    [JsonPropertyName("shape_ids")]
    public SortedDictionary<string, int> ShapeIds { get; set; } = new(StringComparer.Ordinal);

    /// <summary>
    /// The id of each <c>slot:shape</c> pair, under the same rule.
    /// </summary>
    [JsonPropertyName("reverse_ids")]
    public SortedDictionary<string, int> ReverseIds { get; set; } = new(StringComparer.Ordinal);

    /// <summary>
    /// What each run contributed, by the family of packages it generates.
    /// Keeping them apart is what makes re-running one of them idempotent.
    /// </summary>
    /// <remarks>
    /// A family is one metadata source projected into one directory, which is
    /// what a run is, so the directory it writes into is what names the
    /// fragment. The Python package the family publishes into does not: the
    /// Windows SDK, the Windows App SDK and WebView2 all publish into
    /// <c>winrt</c>, and keying by that would let one of them overwrite
    /// another's shapes.
    /// </remarks>
    [JsonPropertyName("families")]
    public SortedDictionary<string, CensusFragment> Families { get; set; } =
        new(StringComparer.Ordinal);

    private static readonly JsonSerializerOptions jsonOptions = new()
    {
        WriteIndented = true,
        IndentSize = 4,
        NewLine = "\n",
    };

    /// <summary>
    /// The oldest revision of this census that has every id below
    /// <paramref name="shapes"/> and <paramref name="reverseShapes"/>.
    /// </summary>
    /// <remarks>
    /// Ids are append-only and handed out in order, so how many there were at
    /// the end of a revision is all it takes to say whether that revision had
    /// a given one. A table that names none is readable by any runtime of
    /// this lineage and gets the first revision.
    /// </remarks>
    public int RevisionFor(int shapes, int reverseShapes)
    {
        for (var i = 0; i < Revisions.Count; i++)
        {
            if (Revisions[i].Shapes >= shapes && Revisions[i].ReverseShapes >= reverseShapes)
            {
                return i + 1;
            }
        }

        throw new InvalidOperationException(
            $"no revision of census {Lineage} has {shapes} shapes and {reverseShapes} reverse shapes"
        );
    }

    public static string ToReverseKey(int slot, string shapeKey) => $"{slot}:{shapeKey}";

    public static (int Slot, string ShapeKey) FromReverseKey(string key)
    {
        var colon = key.IndexOf(':');

        return (int.Parse(key[..colon]), key[(colon + 1)..]);
    }

    public static Census Load(FileInfo file)
    {
        using var stream = file.OpenRead();
        var census =
            JsonSerializer.Deserialize<Census>(stream, jsonOptions)
            ?? throw new FormatException($"{file.FullName} is empty");

        if (census.Version != CurrentVersion)
        {
            throw new FormatException(
                $"{file.FullName} is version {census.Version}, expected {CurrentVersion}"
            );
        }

        if (census.Lineage.Length == 0)
        {
            throw new FormatException($"{file.FullName} does not say which census it is");
        }

        // A table says which revision it needs by looking its ids up in this
        // list, so a census that has not kept one for every revision cannot
        // be written against.
        if (census.Revisions.Count != census.Revision)
        {
            throw new FormatException(
                $"{file.FullName} is revision {census.Revision} and records how far"
                    + $" {census.Revisions.Count} of them got"
            );
        }

        return census;
    }

    /// <summary>
    /// Loads the census in <paramref name="file"/>, or starts one when the
    /// file is not there.
    /// </summary>
    /// <remarks>
    /// Starting one is right for exactly one kind of run: one that also writes
    /// the <c>shapes-generated.h</c> the ids are resolved through, which is
    /// this repository's own. Every other run reads a census someone else
    /// wrote and refuses to invent one, because ids assigned in a run's own
    /// order mean something else to the runtime that resolves them.
    /// </remarks>
    public static Census LoadOrCreate(FileInfo file) =>
        file.Exists ? Load(file) : new Census { Lineage = Guid.NewGuid().ToString() };

    public void Save(DirectoryInfo path, string fileName)
    {
        FileContent.WriteIfChanged(
            path,
            fileName,
            sink =>
            {
                using var stream = new MemoryStream();
                using (
                    var writer = new Utf8JsonWriter(
                        stream,
                        new JsonWriterOptions
                        {
                            Indented = true,
                            IndentSize = 4,
                            NewLine = "\n",
                        }
                    )
                )
                {
                    JsonSerializer.Serialize(writer, this, jsonOptions);
                }

                sink.Write(stream.GetBuffer().AsSpan(0, (int)stream.Length));
                sink.Write("\n"u8);
            }
        );
    }

    /// <summary>
    /// Replaces what <paramref name="family"/> contributed with
    /// <paramref name="fragment"/> and gives an id to every shape that does not
    /// have one yet.
    /// </summary>
    public void Merge(string family, CensusFragment fragment)
    {
        Families[family] = fragment;

        // The all-integer shapes are instantiated for every arity up to the
        // census maximum whether or not the metadata has them, so that a
        // third-party component whose members only pass pointers, integers and
        // enums needs no new trampoline.
        var maxArity = Families
            .Values.SelectMany(p => p.Forward.Keys)
            .Select(k => AbiShape.Parse(k).Args.Count)
            .DefaultIfEmpty(0)
            .Max();

        var forward = Families
            .Values.SelectMany(p => p.Forward.Keys)
            .Concat(Enumerable.Range(0, maxArity + 1).Select(n => new string('p', n)))
            .Distinct(StringComparer.Ordinal);

        var assignedForward = AssignIds(ShapeIds, forward, k => (AbiShape.Parse(k).Args.Count, k));
        var assignedReverse = AssignIds(
            ReverseIds,
            Families.Values.SelectMany(p => p.Reverse),
            k =>
            {
                var (slot, shapeKey) = FromReverseKey(k);
                return (slot, shapeKey);
            }
        );

        // The revision counts appends and nothing else, so a run that finds
        // every shape already numbered leaves the file byte-identical and
        // every table that names this revision keeps naming it.
        if (assignedForward || assignedReverse)
        {
            Revision++;
            Revisions.Add(
                new CensusRevision { Shapes = ShapeIds.Count, ReverseShapes = ReverseIds.Count }
            );
        }
    }

    /// <summary>
    /// Numbers the keys of <paramref name="keys"/> that <paramref name="ids"/>
    /// does not have yet, and says whether there were any.
    /// </summary>
    private static bool AssignIds<TKey>(
        SortedDictionary<string, int> ids,
        IEnumerable<string> keys,
        Func<string, TKey> order
    )
    {
        var next = ids.Count == 0 ? 0 : ids.Values.Max() + 1;
        var assigned = false;

        foreach (var key in keys.Where(k => !ids.ContainsKey(k)).OrderBy(order).ToList())
        {
            ids[key] = next++;
            assigned = true;
        }

        return assigned;
    }

    /// <summary>
    /// Writes a warning for every shape <paramref name="fragment"/> needs that
    /// this census does not have, and answers how many there were.
    /// </summary>
    /// <remarks>
    /// This is what a run that only reads a census does instead of extending
    /// it. The members involved are still projected, so what the author loses
    /// is those calls rather than the whole namespace, and what they need in
    /// order to get them back is the list of shapes below.
    /// </remarks>
    public int ReportMissing(CensusFragment fragment, TextWriter w)
    {
        var forward = fragment.Forward.Where(kv => !ShapeIds.ContainsKey(kv.Key)).ToList();
        var reverse = fragment.Reverse.Where(k => !ReverseIds.ContainsKey(k)).ToList();

        foreach (var (key, count) in forward)
        {
            w.WriteLine(
                $"warning: the ABI call shape ({(key.Length == 0 ? "" : key)}) is not in the "
                    + $"shape census, so the {count} member(s) that make that call cannot be "
                    + "called"
            );
        }

        foreach (var key in reverse)
        {
            var (slot, shapeKey) = FromReverseKey(key);

            w.WriteLine(
                $"warning: the shape census has no callback for slot {slot} with the ABI call "
                    + $"shape ({(shapeKey.Length == 0 ? "" : shapeKey)}), so a member in that "
                    + "slot cannot be implemented in Python"
            );
        }

        return forward.Count + reverse.Count;
    }

    /// <summary>
    /// Gets the forward shapes in id order.
    /// </summary>
    public IReadOnlyList<(int Id, AbiShape Shape)> GetShapes() =>
        [.. ShapeIds.OrderBy(kv => kv.Value).Select(kv => (kv.Value, AbiShape.Parse(kv.Key)))];

    /// <summary>
    /// Gets the reverse trampolines in id order.
    /// </summary>
    public IReadOnlyList<(int Id, int Slot, AbiShape Shape)> GetReverseShapes() =>
        [
            .. ReverseIds
                .OrderBy(kv => kv.Value)
                .Select(kv =>
                {
                    var (slot, shapeKey) = FromReverseKey(kv.Key);
                    return (kv.Value, slot, AbiShape.Parse(shapeKey));
                }),
        ];

    /// <summary>
    /// Gets the by-value struct layouts and the WinRT structs that have them.
    /// </summary>
    public IReadOnlyList<(AbiStructLayout Layout, IReadOnlyCollection<string> Names)> GetStructs()
    {
        var names = new SortedDictionary<string, SortedSet<string>>(StringComparer.Ordinal);

        foreach (var (key, winrtNames) in Families.Values.SelectMany(p => p.Structs))
        {
            if (!names.TryGetValue(key, out var merged))
            {
                merged = new SortedSet<string>(StringComparer.Ordinal);
                names[key] = merged;
            }

            merged.UnionWith(winrtNames);
        }

        // A layout that no package mentions any more still has to be spelled,
        // because a shape that uses it keeps its id.
        foreach (
            var key in GetShapes()
                .SelectMany(s => s.Shape.Args)
                .Where(a => a.Struct is not null)
                .Select(a => a.Struct!.Key)
        )
        {
            names.TryAdd(key, new SortedSet<string>(StringComparer.Ordinal));
        }

        return
        [
            .. names.Select(kv =>
                (
                    (AbiStructLayout)AbiStructLayout.Parse(kv.Key),
                    (IReadOnlyCollection<string>)kv.Value
                )
            ),
        ];
    }

    /// <summary>
    /// Writes the census as a human readable report.
    /// </summary>
    public void WriteReport(TextWriter w)
    {
        var shapes = GetShapes();
        var reverse = GetReverseShapes();
        var structs = GetStructs();
        var counts = new SortedDictionary<string, int>(StringComparer.Ordinal);

        foreach (var (key, count) in Families.Values.SelectMany(p => p.Forward))
        {
            counts[key] = counts.GetValueOrDefault(key) + count;
        }

        var members = counts.Values.Sum();

        w.WriteLine("ABI shape census");
        w.WriteLine();
        w.WriteLine($"  families                     {Families.Count, 8}");
        w.WriteLine($"  forward members walked       {members, 8}");
        w.WriteLine($"  distinct forward shapes      {shapes.Count, 8}");
        w.WriteLine(
            $"  max arity (ABI arguments)    {shapes.Select(s => s.Shape.Args.Count).DefaultIfEmpty(0).Max(), 8}"
        );
        w.WriteLine($"  struct-by-value layouts      {structs.Count, 8}");
        w.WriteLine(
            $"  implementable interfaces     {Families.Values.Sum(p => p.ImplementableInterfaces), 8}"
        );
        w.WriteLine($"  delegates                    {Families.Values.Sum(p => p.Delegates), 8}");
        w.WriteLine($"  distinct (shape, slot) pairs {reverse.Count, 8}");
        w.WriteLine();
        w.WriteLine("  trampolines left after the linker folds identical bodies:");
        w.WriteLine("            forward  reverse");
        WriteFoldRow(w, "x64", shapes, reverse, s => s.GetX64FoldKey());
        WriteFoldRow(w, "arm64", shapes, reverse, s => s.GetArm64FoldKey());
        WriteFoldRow(w, "x86", shapes, reverse, s => s.GetX86FoldKey());
        w.WriteLine();
        w.WriteLine("  struct-by-value layouts (size/align on x64 and on x86):");

        foreach (var (layout, names) in structs)
        {
            w.WriteLine(
                $"    {layout.Key, -26} {layout.GetSize(8), 3}/{layout.GetAlign(8), -2} "
                    + $"{layout.GetSize(4), 3}/{layout.GetAlign(4), -2} "
                    + $"{(layout.IsHomogeneousFloatAggregate ? "hfa" : "   ")} "
                    + $"{string.Join(", ", names.Take(2))}"
                    + $"{(names.Count > 2 ? $", +{names.Count - 2} more" : "")}"
            );
        }

        w.WriteLine();
        w.WriteLine("  the fifteen most common forward shapes:");

        foreach (var (key, count) in counts.OrderByDescending(kv => kv.Value).Take(15))
        {
            var share = members == 0 ? 0 : 100.0 * count / members;
            w.WriteLine($"    {(key.Length == 0 ? "()" : key), -26} {count, 8} {share, 5:F1} %");
        }
    }

    private static void WriteFoldRow(
        TextWriter w,
        string arch,
        IReadOnlyList<(int Id, AbiShape Shape)> shapes,
        IReadOnlyList<(int Id, int Slot, AbiShape Shape)> reverse,
        Func<AbiShape, string> fold
    )
    {
        var forwardCount = shapes
            .Select(s => fold(s.Shape))
            .Distinct(StringComparer.Ordinal)
            .Count();
        var reverseCount = reverse.Select(s => (s.Slot, Key: fold(s.Shape))).Distinct().Count();

        w.WriteLine($"    {arch, -8} {forwardCount, 7}  {reverseCount, 7}");
    }

    /// <summary>
    /// Writes the trampoline instantiations that <c>winrt-runtime</c> compiles.
    /// </summary>
    public void WriteShapesHeader(DirectoryInfo path, string fileName)
    {
        using var sw = new StringWriter();
        using var w = new IndentedTextWriter(sw) { NewLine = "\n" };

        w.WriteLicense();
        w.WriteBlankLine();
        w.WriteLine("// The ABI call shapes of every winmd the tree projects, taken by");
        w.WriteLine("// PyWinRT.exe while it generates and merged in shapes.json. See");
        w.WriteLine("// runtime/src/table-format.md for what a shape is, why the set of them is");
        w.WriteLine("// fixed at build time, and why an id is never renumbered.");
        w.WriteBlankLine();
        w.WriteLine("#pragma once");
        w.WriteBlankLine();
        w.WriteLine("#include \"shapes.h\"");
        w.WriteBlankLine();
        w.WriteLine("// clang-format off");
        w.WriteBlankLine();
        w.WriteLine("namespace py::shapes");
        w.WriteLine("{");
        w.Indent++;
        w.WriteLine("// Which census these trampolines were instantiated from. A table carries");
        w.WriteLine("// the same pair, and a runtime refuses one whose lineage is not this or");
        w.WriteLine("// whose revision is ahead of this, because a shape id only means what it");
        w.WriteLine("// was assigned to mean in the census that issued it.");
        w.WriteBlankLine();
        w.WriteLine($"inline constexpr char census_lineage[] = \"{Lineage}\";");
        w.WriteLine($"inline constexpr uint32_t census_revision = {Revision};");
        w.WriteBlankLine();
        w.WriteLine("// The struct layouts that appear as by-value arguments. A calling");
        w.WriteLine("// convention looks at the field types and the alignment and not only at");
        w.WriteLine("// the size, so each one is spelled faithfully and the compiler decides");
        w.WriteLine("// how it travels.");
        w.WriteBlankLine();

        foreach (var (layout, names) in GetStructs())
        {
            w.Write($"struct {layout.CppName} {{ ");

            for (var i = 0; i < layout.Fields.Count; i++)
            {
                w.Write($"{layout.Fields[i].ToCppType()} f{i}; ");
            }

            w.WriteLine($"}}; // {string.Join(", ", names)}");
        }

        w.WriteBlankLine();
        w.WriteLine("// Forward: one entry per shape, indexed by the shape id in the table.");
        w.WriteBlankLine();
        w.WriteLine("inline constexpr shape_desc forward_shapes[] = {");
        w.Indent++;

        foreach (var (id, shape) in GetShapes())
        {
            w.WriteLine(
                $"make_shape<{shape.ToCppArgumentList()}>(), // {id}: ({(shape.Key.Length == 0 ? "" : shape.Key)})"
            );
        }

        w.Indent--;
        w.WriteLine("};");
        w.WriteBlankLine();
        w.WriteLine("// Reverse: one entry per (shape, slot), because a vtable entry cannot");
        w.WriteLine("// learn in portable C++ which slot it was called through.");
        w.WriteBlankLine();
        w.WriteLine("inline const reverse_desc reverse_shapes[] = {");
        w.Indent++;

        foreach (var (id, slot, shape) in GetReverseShapes())
        {
            w.WriteLine(
                $"make_reverse<{slot}{(shape.Args.Count > 0 ? ", " : "")}{shape.ToCppArgumentList()}>(),"
                    + $" // {id}: slot {slot}, ({shape.Key})"
            );
        }

        w.Indent--;
        w.WriteLine("};");
        w.Indent--;
        w.WriteBlankLine();
        w.WriteLine("} // namespace py::shapes");
        w.WriteBlankLine();
        w.WriteLine("// clang-format on");

        sw.WriteFileIfChanged(path, fileName);
    }
}
