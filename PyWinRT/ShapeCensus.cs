using Mono.Cecil;

/// <summary>
/// The ABI call shapes that appear in the metadata of one generator run.
/// </summary>
/// <remarks>
/// The table driven projection calls WinRT through a trampoline chosen by a
/// member's ABI shape, and the trampolines are compiled into winrt-runtime, so
/// the runtime has to know every shape ahead of time. This walks all of the
/// metadata of one run - not a sample, and including the interfaces that are
/// exclusive to a runtime class and so are never projected as a Python type but
/// are still what a call goes through.
///
/// One run is not the whole census: WinUI 2 and the Windows App SDK both define
/// <c>Microsoft.UI.Xaml.Controls</c>, so they cannot be loaded into one metadata
/// resolver and each is generated by a run of its own. <see cref="Census"/>
/// merges what the runs find.
/// </remarks>
sealed class ShapeCensus
{
    private readonly AbiShapeReader reader = new();

    /// <summary>
    /// Interfaces and delegates that have already been walked, by name plus
    /// type arguments, since the same one is reached from many types.
    /// </summary>
    private readonly HashSet<string> visitedForward = new(StringComparer.Ordinal);
    private readonly HashSet<string> visitedReverse = new(StringComparer.Ordinal);

    private readonly CensusFragment fragment = new();

    /// <summary>
    /// The vtable slot of the first method of a WinRT interface, after the three
    /// IUnknown and three IInspectable entries.
    /// </summary>
    public const int FirstInterfaceSlot = 6;

    /// <summary>
    /// The vtable slot of a delegate's Invoke, after the three IUnknown entries.
    /// A delegate does not derive from IInspectable.
    /// </summary>
    public const int DelegateInvokeSlot = 3;

    /// <summary>
    /// Walks <paramref name="types"/> and everything they mention, and returns
    /// what this run contributes to the census.
    /// </summary>
    public CensusFragment Take(IEnumerable<TypeDefinition> types)
    {
        var typeList = types.ToList();

        foreach (var type in typeList)
        {
            switch (type.GetCategory())
            {
                case Category.Interface:
                    AddInterface(type, type.FullName, null, implementable: !type.IsExclusiveTo);
                    break;
                case Category.Delegate:
                    AddDelegate(type, type.FullName, null);
                    break;
                case Category.Class:
                    // A class calls through its interfaces, which are walked
                    // above, but the interfaces it lets Python override are
                    // exclusive to it, so they are only reachable from here.
                    foreach (var iface in type.Interfaces)
                    {
                        if (
                            !iface.CustomAttributes.Any(a =>
                                a.AttributeType.FullName
                                    == "Windows.Foundation.Metadata.OverridableAttribute"
                                || a.AttributeType.FullName
                                    == "Windows.Foundation.Metadata.ProtectedAttribute"
                            )
                        )
                        {
                            continue;
                        }

                        var definition = iface.InterfaceType.TryResolve();

                        if (definition is not null)
                        {
                            AddInterface(
                                definition,
                                iface.InterfaceType.FullName,
                                GetGenericMap(iface.InterfaceType, definition),
                                implementable: true
                            );
                        }
                    }
                    break;
            }
        }

        foreach (var instance in CollectGenericInstances(typeList))
        {
            var definition = instance.ElementType.TryResolve();

            if (definition is null)
            {
                continue;
            }

            var map = GetGenericMap(instance, definition);
            var name = instance.ToWinRtName();

            switch (definition.GetCategory())
            {
                case Category.Interface:
                    AddInterface(definition, name, map, implementable: !definition.IsExclusiveTo);
                    break;
                case Category.Delegate:
                    AddDelegate(definition, name, map);
                    break;
            }
        }

        foreach (var layout in reader.Structs.Values)
        {
            fragment.Structs[layout.Key] = layout.WinRtNames;
        }

        return fragment;
    }

    private void AddInterface(
        TypeDefinition definition,
        string name,
        IReadOnlyDictionary<GenericParameter, TypeReference>? map,
        bool implementable
    )
    {
        if (visitedForward.Add(name))
        {
            foreach (var method in definition.Methods)
            {
                AddForward(method, map);
            }
        }

        if (!implementable || !visitedReverse.Add(name))
        {
            return;
        }

        fragment.ImplementableInterfaces++;

        for (var i = 0; i < definition.Methods.Count; i++)
        {
            AddReverse(definition.Methods[i], map, FirstInterfaceSlot + i);
        }
    }

    private void AddDelegate(
        TypeDefinition definition,
        string name,
        IReadOnlyDictionary<GenericParameter, TypeReference>? map
    )
    {
        var invoke = definition.Methods.FirstOrDefault(m => m.Name == "Invoke");

        if (invoke is null)
        {
            return;
        }

        if (visitedForward.Add(name))
        {
            AddForward(invoke, map);
        }

        if (!visitedReverse.Add(name))
        {
            return;
        }

        fragment.Delegates++;

        AddReverse(invoke, map, DelegateInvokeSlot);
    }

    private void AddForward(
        MethodDefinition method,
        IReadOnlyDictionary<GenericParameter, TypeReference>? map
    )
    {
        var shape = reader.GetShape(method, map);

        if (shape is null)
        {
            return;
        }

        fragment.Forward[shape.Key] = fragment.Forward.GetValueOrDefault(shape.Key) + 1;
    }

    private void AddReverse(
        MethodDefinition method,
        IReadOnlyDictionary<GenericParameter, TypeReference>? map,
        int slot
    )
    {
        var shape = reader.GetShape(method, map);

        if (shape is null)
        {
            return;
        }

        fragment.Reverse.Add(Census.ToReverseKey(slot, shape.Key));
    }

    private static IReadOnlyDictionary<GenericParameter, TypeReference>? GetGenericMap(
        TypeReference reference,
        TypeDefinition definition
    ) =>
        reference is GenericInstanceType generic
            ? definition.GenericParameters.Zip(generic.GenericArguments).ToDictionary()
            : null;

    /// <summary>
    /// Gets every closed parameterized interface or delegate instance that
    /// appears anywhere in <paramref name="types"/>, including the arguments of
    /// other instances and the related instances the runtime uses to implement
    /// them.
    /// </summary>
    private static IReadOnlyCollection<GenericInstanceType> CollectGenericInstances(
        IReadOnlyCollection<TypeDefinition> types
    )
    {
        var instances = new SortedDictionary<string, GenericInstanceType>(StringComparer.Ordinal);

        void collect(TypeReference type)
        {
            while (
                type is ByReferenceType or ArrayType or OptionalModifierType or RequiredModifierType
            )
            {
                type = ((TypeSpecification)type).ElementType;
            }

            if (type is not GenericInstanceType generic || !IsConcrete(generic))
            {
                return;
            }

            if (!instances.TryAdd(generic.ToWinRtName(), generic))
            {
                return;
            }

            foreach (var argument in generic.GenericArguments)
            {
                collect(argument);
            }

            foreach (var related in WinRtGuid.GetRelatedInstances(generic))
            {
                collect(related);
            }
        }

        foreach (var type in types)
        {
            foreach (var method in type.Methods)
            {
                foreach (var parameter in method.Parameters)
                {
                    collect(parameter.ParameterType);
                }

                collect(method.ReturnType);
            }

            foreach (var iface in type.Interfaces)
            {
                collect(iface.InterfaceType);
            }

            foreach (var field in type.Fields.Where(f => !f.IsStatic))
            {
                collect(field.FieldType);
            }
        }

        return instances.Values;
    }

    private static bool IsConcrete(TypeReference type) =>
        type switch
        {
            GenericParameter => false,
            { FullName: "System.Type" } => false,
            GenericInstanceType generic => generic.GenericArguments.All(IsConcrete),
            TypeSpecification spec => IsConcrete(spec.ElementType),
            _ => true,
        };
}
